package com.github.fabiitch.gdx.lwjgl3;

import java.util.concurrent.TimeUnit;

/** Limits the next iteration using the time already spent rendering this one. */
final class Sync {
    static void afterFrame(long frameStartNanos, int fps) {
        long remaining = 1_000_000_000L / fps - (System.nanoTime() - frameStartNanos);
        if (remaining <= 0) return;
        try {
            TimeUnit.NANOSECONDS.sleep(remaining);
        } catch (InterruptedException ignored) {
            // Return to the application loop so it can check its lifecycle state.
        }
    }
}
